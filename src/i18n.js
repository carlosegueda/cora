export const LOCALES = { en: 'en-US', es: 'es-ES', pt: 'pt-BR' };

let current = 'en';

export const getLanguage = () => current;
export const locale = () => LOCALES[current];

export function t(key, vars = {}) {
  const value = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return typeof value === 'function' ? value(vars) : value;
}

// Traduce los elementos con data-i18n / data-i18n-attr
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of node.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      node.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}

export function setLanguage(code) {
  current = STRINGS[code] ? code : 'en';
  document.documentElement.lang = current;
  applyTranslations();
}
